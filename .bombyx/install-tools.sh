#!/usr/bin/env bash
# User-owned tooling in the development VM; never run as root.
set -euo pipefail
[[ $(id -u) != 0 ]] || { echo 'Install developer tools as the agent user.' >&2; exit 1; }
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
case $(uname -m) in
    x86_64) node_arch=x64; rust_arch=x86_64 ;;
    aarch64) node_arch=arm64; rust_arch=aarch64 ;;
    *) echo 'Only Linux x86_64 and ARM64 are supported.' >&2; exit 1 ;;
esac
tool_root="$HOME/.local/share/silkboard-dev"
node_dir="$tool_root/node-v24.14.1-linux-$node_arch"
export CARGO_HOME="$HOME/.cargo" RUSTUP_HOME="$HOME/.rustup"
export RUSTUP_TOOLCHAIN=1.93.1 CARGO_BUILD_JOBS=2
export PATH="$node_dir/bin:$tool_root/agents/node_modules/.bin:$CARGO_HOME/bin:$PATH"
export DISABLE_AUTOUPDATER=1 DISABLE_UPDATES=1
mkdir -p "$tool_root"
work=$(mktemp -d "$tool_root/.install.XXXXXX")
trap 'rm -rf -- "$work"' EXIT
cd "$work"
verify() {
    awk -v name="$1" '$2 == name {print}' "$root/.bombyx/downloads.sha256" > checksum
    [[ -s checksum ]] || { echo "Missing checksum for $1" >&2; exit 1; }
    sha256sum --check checksum
}
if [[ ! -x $node_dir/bin/node ]]; then
    node_file="node-v24.14.1-linux-$node_arch.tar.xz"
    curl --fail --silent --show-error --location --retry 3 \
        "https://nodejs.org/dist/v24.14.1/$node_file" --output "$node_file"
    verify "$node_file"
    tar -xJf "$node_file" -C "$work"
    mv -T "$work/node-v24.14.1-linux-$node_arch" "$node_dir"
fi
[[ $(node --version) == v24.14.1 ]] || { echo 'Unexpected Node version.' >&2; exit 1; }
if [[ ! -x $CARGO_HOME/bin/rustup ]]; then
    rust_file="rustup-init-$rust_arch"
    curl --fail --silent --show-error --location --retry 3 \
        "https://static.rust-lang.org/rustup/archive/1.28.2/$rust_arch-unknown-linux-gnu/rustup-init" \
        --output "$rust_file"
    verify "$rust_file"
    chmod +x "$rust_file"
    "./$rust_file" -y --no-modify-path --profile minimal --default-toolchain none
fi
rustup toolchain install 1.93.1 --profile minimal \
    --component rustfmt,clippy,llvm-tools-preview --target aarch64-unknown-linux-gnu
cargo install --locked cargo-llvm-cov@0.9.0
cargo install --locked code-dupes@0.2.1
cargo install --locked cargo-deny@0.20.2
cargo install --locked cargo-audit@0.22.2
mkdir -p "$tool_root/agents"
cp "$root/.bombyx/package.json" "$root/.bombyx/package-lock.json" "$tool_root/agents/"
npm ci --prefix "$tool_root/agents" --no-fund
npm audit --prefix "$tool_root/agents" --audit-level=low
# Only the tool environment is managed. Preserve existing agent settings/login.
mkdir -p "$HOME/.config/silkboard"
cat > "$HOME/.config/silkboard/dev-env.sh" <<ENVIRONMENT
# Generated by Silkboard's Bombyx provisioner.
export PATH="\$HOME/.local/share/silkboard-dev/node-v24.14.1-linux-$node_arch/bin:\$HOME/.local/share/silkboard-dev/agents/node_modules/.bin:\$HOME/.cargo/bin:\$PATH"
export CARGO_HOME="\$HOME/.cargo" RUSTUP_HOME="\$HOME/.rustup"
export RUSTUP_TOOLCHAIN=1.93.1 CARGO_BUILD_JOBS=2
export DISABLE_AUTOUPDATER=1 DISABLE_UPDATES=1
ENVIRONMENT
# shellcheck disable=SC2016 # Expand HOME when the future shell reads the line.
profile_line='[ ! -f "$HOME/.config/silkboard/dev-env.sh" ] || . "$HOME/.config/silkboard/dev-env.sh"'
for profile in "$HOME/.profile" "$HOME/.bashrc"; do
    if ! grep -Fqx "$profile_line" "$profile" 2>/dev/null; then
        printf '\n%s\n' "$profile_line" >> "$profile"
    fi
done
